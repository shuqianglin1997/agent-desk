function createWindow() {
  if (mainWindow && !mainWindow.isDestroyed()) return mainWindow;
  mainWindow = new BrowserWindow({
    // Keep the fixed outer dimensions. The renderer toolbar also hosts the
    // native window controls on macOS and Windows.
    width: 1040,
    height: 840,
    resizable: false,
    maximizable: false,
    fullscreenable: false,
    show: false,
    title: APP_NAME,
    ...windowChromeOptions(process.platform, process.platform === 'win32' ? loadSettings().theme : null, nativeTheme.shouldUseDarkColors),
    ...(process.platform === 'win32' ? { icon: path.join(__dirname, '..', 'assets', 'icon.ico') } : {}),
    // 灯还没开时的夜色（与 pixel.css 的 --lamp-night 一致）：窗口在页面画出来之前也不会先闪一下亮的。
    backgroundColor: '#140e11',
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true
    }
  });

  installMainWindowSecurity(mainWindow, {
    allowedUrl: MAIN_DOCUMENT_URL,
    csp: MAIN_DOCUMENT_CSP
  });
  // Tasks that asked to pause while the window is hidden follow it.
  for (const name of ['hide', 'minimize']) mainWindow.on(name, () => mainOwner.setWindowVisible(false));
  for (const name of ['show', 'restore']) mainWindow.on(name, () => mainOwner.setWindowVisible(true));
  windowLamp.attach(mainWindow, { platform: process.platform, isQuitting: () => appQuitting, quit: () => app.quit() });

  mainWindow.once('ready-to-show', () => {
    if (!mainWindow || mainWindow.isDestroyed()) return;
    mainWindow.show();
    mainWindow.focus();
  });
  mainWindow.on('closed', () => {
    void remoteControlService?.stopAll('main-window-closed');
    mainWindow = null;
  });
  // 开发期把渲染层的错误/警告转发到主进程 stdout，便于无 devtools 时自检渲染层健康。
  if (!app.isPackaged) {
    mainWindow.webContents.on('console-message', (_event, level, message, line, sourceId) => {
      if (level >= 2) console.error(`[renderer] ${message} (${String(sourceId).split('/').pop()}:${line})`);
    });
    mainWindow.webContents.on('render-process-gone', (_event, details) => {
      console.error('[renderer-gone]', details && details.reason);
    });
  }

  mainWindow.loadFile(MAIN_DOCUMENT_PATH);
  return mainWindow;
}

function showMainWindow() {
  if (!app.isReady()) return;
  if (!mainWindow || mainWindow.isDestroyed()) {
    createWindow();
    return;
  }
  if (mainWindow.isMinimized()) mainWindow.restore();
  mainWindow.show();
  mainWindow.focus();
}

