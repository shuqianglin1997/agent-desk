#!/usr/bin/env node
'use strict';

// The mainContext block in src/main.js, generated: the one object through
// which code outside main.js reaches Main's services and state.
//   - the commands in src/commands/ take it as `deps` (the names they
//     destructure, or read as deps.<name>);
//   - modules moved out of main.js (src/main/*.js with `bind(context)`) read
//     it as main.<name>.
// Every name is a getter, read when used (no start-up ordering problem);
// Main's `let` state also gets a setter, so moved code that assigns it still
// assigns Main's variable. Commands that run in the CLI process
// (cli-local.js) are skipped.
//
//   node scripts/main-context.js           print the block
//   node scripts/main-context.js --write   replace it in src/main.js
// test/command-table.test.js fails when the block is out of date.

const fs = require('node:fs');
const path = require('node:path');
const { maskSource } = require('./arch-metrics');

const ROOT = path.resolve(__dirname, '..');
const MAIN = path.join(ROOT, 'src', 'main.js');
const SKIP_COMMANDS = new Set(['registry.js', 'events.js', 'cli-local.js']);
const START = '// main context:start — generated by scripts/main-context.js; do not edit by hand';
const END = '// main context:end';

function namesFromCommands(root) {
  const names = new Set();
  const directory = path.join(root, 'src', 'commands');
  for (const file of fs.readdirSync(directory)) {
    if (SKIP_COMMANDS.has(file) || !file.endsWith('.js')) continue;
    const text = fs.readFileSync(path.join(directory, file), 'utf8');
    const lists = [...text.matchAll(/const \{([^}]*)\} = deps;/g), ...text.matchAll(/(?:exec|poll)(?::\s*(?:async\s*)?)?\(\{([^}]*)\}/g)];
    for (const match of lists) {
      for (const part of match[1].split(',')) {
        const name = part.trim().match(/^(\w+)/);
        if (name) names.add(name[1]);
      }
    }
    for (const match of text.matchAll(/\bdeps\.(\w+)/g)) names.add(match[1]);
  }
  return names;
}

// Modules moved out of main.js: src/main/*.js files that export bind().
function namesFromMovedModules(root) {
  const names = new Set();
  const directory = path.join(root, 'src', 'main');
  for (const file of fs.readdirSync(directory)) {
    if (!file.endsWith('.js')) continue;
    const text = fs.readFileSync(path.join(directory, file), 'utf8');
    if (!/^function bind\(context\) \{ main = context; \}$/m.test(text)) continue;
    // Code only: comments and strings may name main.js.
    for (const match of maskSource(text).matchAll(/(?<![\w$.])main\.(\w+)/g)) names.add(match[1]);
  }
  return names;
}

function usedNames(root = ROOT) {
  return new Set([...namesFromCommands(root), ...namesFromMovedModules(root)]);
}

function mainNames(source) {
  const lets = new Set();
  const declared = new Set();
  for (const match of source.matchAll(/^let\s+([^;\n]+)/gm)) {
    for (const part of match[1].split(',')) {
      const name = part.trim().match(/^(\w+)/);
      if (name) { lets.add(name[1]); declared.add(name[1]); }
    }
  }
  for (const match of source.matchAll(/^(?:async\s+)?function\s*\*?\s*(\w+)/gm)) declared.add(match[1]);
  for (const match of source.matchAll(/^(?:const|class)\s+(\w+)/gm)) declared.add(match[1]);
  for (const match of source.matchAll(/^const\s*\{([^}]*)\}\s*=/gm)) {
    for (const part of match[1].split(',')) {
      const text = part.trim();
      const renamed = text.match(/^\w+\s*:\s*(\w+)/);
      const name = renamed ? renamed[1] : (text.match(/^(\w+)/) || [])[1];
      if (name) declared.add(name);
    }
  }
  return { lets, declared };
}

function block(source = fs.readFileSync(MAIN, 'utf8'), root = ROOT) {
  const names = [...usedNames(root)].sort();
  const { lets, declared } = mainNames(source);
  const missing = names.filter((name) => !declared.has(name));
  if (missing.length) throw new Error(`names main.js does not declare at top level: ${missing.join(' ')}`);
  const lines = names.map((name) => (lets.has(name)
    ? `    get ${name}() { return ${name}; }, set ${name}(value) { ${name} = value; },`
    : `    get ${name}() { return ${name}; },`));
  if (lines.length) lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');
  return [
    START,
    '// Main\'s services and state for the commands (src/commands/, as `deps`) and',
    '// the modules moved out of this file (src/main/*.js, as `main`). Getters are',
    '// read when used; Main\'s `let` state also has a setter.',
    'let mainContextCache = null;',
    'function mainContext() {',
    '  if (mainContextCache) return mainContextCache;',
    '  mainContextCache = {',
    ...lines,
    '  };',
    '  return mainContextCache;',
    '}',
    END
  ].join('\n');
}

function current(source = fs.readFileSync(MAIN, 'utf8')) {
  const start = source.indexOf(START);
  const end = source.indexOf(END, start);
  return start < 0 || end < 0 ? null : source.slice(start, end + END.length);
}

function write() {
  const source = fs.readFileSync(MAIN, 'utf8');
  const existing = current(source);
  if (existing === null) throw new Error('src/main.js has no generated mainContext block');
  fs.writeFileSync(MAIN, source.replace(existing, block(source)));
}

module.exports = { block, current, usedNames, START, END };

if (require.main === module) {
  if (process.argv.includes('--write')) write();
  else process.stdout.write(block() + '\n');
}
