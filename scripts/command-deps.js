#!/usr/bin/env node
'use strict';

// The commandDeps block in src/main.js: Main's services that the commands in
// src/commands/ use, generated from what those modules destructure from
// `deps` (state that changes is passed as a getter). Commands that run in the
// CLI process (cli-local.js) get the CLI's own deps and are skipped here.
//
//   node scripts/command-deps.js           print the block
//   node scripts/command-deps.js --write   replace it in src/main.js
// test/command-table.test.js fails when the block is out of date.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MAIN = path.join(ROOT, 'src', 'main.js');
const COMMANDS = path.join(ROOT, 'src', 'commands');
const SKIP = new Set(['registry.js', 'events.js', 'cli-local.js']);
const START = '// command deps:start — generated by scripts/command-deps.js; do not edit by hand';
const END = '// command deps:end';

// Every name a command module takes from deps.
function usedNames(root = ROOT) {
  const names = new Set();
  const directory = path.join(root, 'src', 'commands');
  for (const file of fs.readdirSync(directory)) {
    if (SKIP.has(file) || !file.endsWith('.js')) continue;
    const text = fs.readFileSync(path.join(directory, file), 'utf8');
    const lists = [...text.matchAll(/const \{([^}]*)\} = deps;/g), ...text.matchAll(/(?:exec|poll)(?::\s*(?:async\s*)?)?\(\{([^}]*)\}/g), ...text.matchAll(/\bdeps\.(\w+)/g)];
    for (const match of lists) {
      for (const part of match[1].split(',')) {
        const name = part.trim().match(/^(\w+)/);
        if (name) names.add(name[1]);
      }
    }
  }
  return names;
}

function mainNames(source) {
  const lets = new Set();
  const declared = new Set();
  for (const match of source.matchAll(/^let\s+([^;\n]+)/gm)) {
    for (const part of match[1].split(',')) {
      const name = part.trim().match(/^(\w+)/);
      if (name) { lets.add(name[1]); declared.add(name[1]); }
    }
  }
  for (const match of source.matchAll(/^(?:async\s+)?function\s*\*?\s*(\w+)/gm)) declared.add(match[1]);
  for (const match of source.matchAll(/^(?:const|class)\s+(\w+)/gm)) declared.add(match[1]);
  for (const match of source.matchAll(/^const\s*\{([^}]*)\}\s*=/gm)) {
    for (const part of match[1].split(',')) {
      const text = part.trim();
      const renamed = text.match(/^\w+\s*:\s*(\w+)/);
      const name = renamed ? renamed[1] : (text.match(/^(\w+)/) || [])[1];
      if (name) declared.add(name);
    }
  }
  return { lets, declared };
}

function block(source = fs.readFileSync(MAIN, 'utf8'), root = ROOT) {
  const names = usedNames(root);
  const { lets, declared } = mainNames(source);
  const missing = [...names].filter((name) => !declared.has(name));
  if (missing.length) throw new Error(`commands use names main.js does not declare at top level: ${missing.join(' ')}`);
  const plain = [...names].filter((name) => !lets.has(name)).sort();
  const getters = [...names].filter((name) => lets.has(name)).sort();
  const lines = [];
  let line = '   ';
  for (const name of plain) {
    if ((`${line} ${name},`).length > 110) { lines.push(line); line = '   '; }
    line += ` ${name},`;
  }
  if (line.trim()) lines.push(line);
  for (const name of getters) lines.push(`    get ${name}() { return ${name}; },`);
  if (lines.length) lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');
  return [
    START,
    '// Main\'s services the commands in src/commands/ use; getters for state that',
    '// changes. Built on first use, after every name here is initialized.',
    'let commandDepsCache = null;',
    'function commandDeps() {',
    '  if (commandDepsCache) return commandDepsCache;',
    '  commandDepsCache = {',
    ...lines,
    '  };',
    '  return commandDepsCache;',
    '}',
    END
  ].join('\n');
}

function current(source = fs.readFileSync(MAIN, 'utf8')) {
  const start = source.indexOf(START);
  const end = source.indexOf(END, start);
  return start < 0 || end < 0 ? null : source.slice(start, end + END.length);
}

function write() {
  const source = fs.readFileSync(MAIN, 'utf8');
  const existing = current(source);
  if (existing === null) throw new Error('src/main.js has no generated commandDeps block');
  fs.writeFileSync(MAIN, source.replace(existing, block(source)));
}

module.exports = { block, current, usedNames, START, END };

if (require.main === module) {
  if (process.argv.includes('--write')) write();
  else process.stdout.write(block() + '\n');
}
