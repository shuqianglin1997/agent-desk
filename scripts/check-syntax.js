function checkFile(file) {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, ['--check', file], {
      cwd: ROOT,
      stdio: ['ignore', 'ignore', 'pipe'],
      windowsHide: true
    });
    let stderr = '';
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.on('error', (error) => resolve({ file, ok: false, output: String(error?.message || error) }));
    child.on('close', (code) => resolve({ file, ok: code === 0, output: stderr.trim() }));
  });
}

// Runs the checks a few at a time and reports failures in list order.
async function checkFiles(files = FILES, concurrency = Math.max(1, Math.min(8, os.availableParallelism?.() || os.cpus().length))) {
  const results = new Array(files.length);
  let next = 0;
  async function worker() {
    while (next < files.length) {
      const index = next;
      next += 1;
      results[index] = await checkFile(files[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, files.length) }, worker));
  return results;
}

async function main() {
  const failures = (await checkFiles()).filter((result) => !result.ok);
  for (const failure of failures) {
    process.stderr.write(`node --check ${failure.file} failed\n${failure.output}\n\n`);
  }
  if (failures.length) {
    process.stderr.write(`${failures.length} of ${FILES.length} files failed the syntax check\n`);
    process.exitCode = 1;
    return;
  }
  process.stdout.write(`node --check passed for ${FILES.length} files\n`);
}

if (require.main === module) {
  main().catch((error) => {
    process.stderr.write(`${error?.stack || error}\n`);
    process.exitCode = 1;
  });
}

module.exports = { FILES, checkFiles };
