#!/usr/bin/env node
'use strict';

// The IPC list in docs/INTERNAL.md §7, generated from the command table
// (src/commands/registry.js). scripts/check-docs.js fails when the section is
// not what this prints.
//
//   node scripts/command-docs.js           print the section
//   node scripts/command-docs.js --write   replace it in docs/INTERNAL.md

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const DOC = path.join(ROOT, 'docs', 'INTERNAL.md');
const START = '<!-- commands:start — generated by scripts/command-docs.js from src/commands/; do not edit by hand -->';
const END = '<!-- commands:end -->';

function code(value) {
  return `\`${value}\``;
}

function section(table = require('../src/commands/registry').commandTable()) {
  const lines = [START, ''];
  lines.push(`窗口能向 Main 发起的命令 ${table.commands.length} 条，都在命令表里、经命令表的薄壳注册；Main 发给窗口的通知 ${table.events.length} 条。`);
  lines.push('');
  lines.push('| 功能 | 命令 | 通道 | preload | 定义在 |');
  lines.push('|---|---|---|---|---|');
  for (const command of table.commands) {
    lines.push(`| ${command.feature} | ${code(command.id)} | ${code(command.channel)} | ${command.preload.map(code).join(' ')} | ${code(command.module)} |`);
  }
  lines.push('');
  lines.push('| Main → 窗口的通知 | preload |');
  lines.push('|---|---|');
  for (const event of table.events) lines.push(`| ${code(event.channel)} | ${event.preload.map(code).join(' ')} |`);
  lines.push('', END);
  return lines.join('\n');
}

// The section as it stands in the document, or null when the markers are missing.
function current(text = fs.readFileSync(DOC, 'utf8')) {
  const start = text.indexOf(START);
  const end = text.indexOf(END, start);
  if (start < 0 || end < 0) return null;
  return text.slice(start, end + END.length);
}

function write() {
  const text = fs.readFileSync(DOC, 'utf8');
  const existing = current(text);
  if (existing === null) throw new Error('docs/INTERNAL.md has no generated command section');
  fs.writeFileSync(DOC, text.replace(existing, section()));
}

module.exports = { section, current, START, END };

if (require.main === module) {
  if (process.argv.includes('--write')) write();
  else process.stdout.write(section() + '\n');
}
